//! Detection, installation and removal of the two runtime dependencies.
//!
//! * WinFsp — the user-mode file system driver/framework (row 1).
//! * SSHFS-Win — the SSH file system service that plugs into WinFsp (row 2).
//!
//! Both are detected through their registry keys (32-bit view, which is where
//! WinFsp/SSHFS-Win register themselves) with a file-system fallback, so an
//! installation that skipped the registry entries is still recognized.
//!
//! The Nix package embeds the pinned WinFsp installer and both the 64-bit and
//! 32-bit SSHFS-Win installers into the wizard executable; the SSHFS-Win one
//! matching the running OS is picked at install time. [`install_winfsp`] and
//! [`install_sshfs`] extract that MSI to the user's temporary directory and
//! hand it to `msiexec`. Builds without embedded installers fall back to an
//! MSI in a `deps/` directory next to the executable, then `winget`, and
//! finally the upstream download pages.

use std::path::{Path, PathBuf};

use crate::registry;
use crate::win32;

/// MSI embedded at build time: its file name and the raw bytes.
type EmbeddedInstaller = (&'static str, &'static [u8]);

// Generated by `build.rs`. Each constant is `None` unless the build exported
// `WINFSP_INSTALLER` / `SSHFS_WIN_X64_INSTALLER` / `SSHFS_WIN_X86_INSTALLER`
// with the MSI path.
include!(concat!(env!("OUT_DIR"), "/embedded_installers.rs"));

#[derive(Clone, Copy, Default)]
pub struct Status {
    pub winfsp: bool,
    pub sshfs: bool,
    pub keepalive: bool,
}

impl Status {
    /// Whether the file-system stack (driver and client) is installed. The
    /// keepalive options are desirable but not required for a mapping.
    pub fn ready(&self) -> bool {
        self.winfsp && self.sshfs
    }
}

pub fn check() -> Status {
    let winfsp = winfsp_installed();
    let sshfs = sshfs_installed();
    let keepalive = registry::keepalive_configured();
    let status = Status {
        winfsp,
        sshfs,
        keepalive,
    };

    crate::log::line("---- 依赖状态检查 ----");
    crate::log::line(format!(
        "WinFsp={winfsp}，SSHFS-Win={sshfs}，断线自动重连={keepalive}，整体就绪={}",
        status.ready()
    ));
    crate::log::line(format!(
        "WinFsp 注册表项存在：{}",
        registry::key_exists(registry::WINFSP_KEY)
    ));
    crate::log::line(format!(
        "SSHFS-Win 服务注册表项存在：{}",
        registry::key_exists(registry::SSHFS_SERVICE_KEY)
    ));
    log_file_probe("WinFsp", winfsp_files());
    log_file_probe("SSHFS-Win", sshfs_files());
    registry::log_state();

    status
}

/// Writes every probed installation file and whether it exists to the log, so
/// a failed detection shows exactly which paths were looked at.
fn log_file_probe(component: &str, paths: Vec<PathBuf>) {
    for path in paths {
        crate::log::line(format!(
            "{component} 安装文件 {}：{}",
            path.display(),
            if path.is_file() { "存在" } else { "不存在" }
        ));
    }
}

fn env_file(variable: &str, relative: &str) -> Option<PathBuf> {
    std::env::var_os(variable).map(|base| PathBuf::from(base).join(relative))
}

/// Whether the OS itself is 64-bit, even when this process is a 32-bit one
/// running under WOW64. The native system info reports the architecture of the
/// machine, unlike `GetSystemInfo`, which reports the emulated one.
pub fn is_os_64bit() -> bool {
    use winsafe::co::PROCESSOR_ARCHITECTURE;

    let info = winsafe::GetNativeSystemInfo();
    matches!(
        info.wProcessorArchitecture,
        PROCESSOR_ARCHITECTURE::AMD64
            | PROCESSOR_ARCHITECTURE::ARM64
            | PROCESSOR_ARCHITECTURE::IA64
    )
}

/// WinFsp launcher paths probed when the registry key is missing.
fn winfsp_files() -> Vec<PathBuf> {
    ["ProgramFiles(x86)", "ProgramFiles", "ProgramW6432"]
        .iter()
        .flat_map(|variable| {
            [
                env_file(variable, r"WinFsp\bin\launcher-x64.exe"),
                env_file(variable, r"WinFsp\bin\launcher-x86.exe"),
            ]
        })
        .flatten()
        .collect()
}

/// SSHFS-Win client paths probed when the service key is missing.
fn sshfs_files() -> Vec<PathBuf> {
    ["ProgramFiles", "ProgramW6432", "ProgramFiles(x86)"]
        .iter()
        .filter_map(|variable| env_file(variable, r"SSHFS-Win\bin\sshfs.exe"))
        .collect()
}

fn winfsp_installed() -> bool {
    registry::key_exists(registry::WINFSP_KEY) || winfsp_files().iter().any(|path| path.is_file())
}

fn sshfs_installed() -> bool {
    registry::key_exists(registry::SSHFS_SERVICE_KEY)
        || sshfs_files().iter().any(|path| path.is_file())
}

/// Full path of `winget.exe`, resolved through `where` because the Windows
/// Apps execution alias is not a real file next to the other system tools.
fn winget_path() -> Option<String> {
    let output = win32::command("where.exe").arg("winget").output().ok()?;
    if !output.status.success() {
        return None;
    }
    String::from_utf8_lossy(&output.stdout)
        .lines()
        .map(str::trim)
        .find(|line| !line.is_empty())
        .map(str::to_owned)
}

/// Directory holding the running wizard, i.e. where the single-file
/// `aidesk-mount-wizard.exe` was downloaded to.
fn exe_dir() -> Option<PathBuf> {
    let exe = std::env::current_exe().ok()?;
    exe.parent().map(Path::to_path_buf)
}

/// Directories searched for the bundled MSI installers, in order: a `deps/`
/// subdirectory next to the executable, then the executable's own directory so
/// a hand-assembled bundle (or one unpacked from an older flat archive) still
/// works. The official download embeds every MSI, so this is only a fallback.
fn installer_dirs() -> Vec<PathBuf> {
    match exe_dir() {
        Some(dir) => vec![dir.join("deps"), dir],
        None => Vec::new(),
    }
}

/// Finds the installer in `dir` whose file name starts with `prefix` and ends
/// in `suffix` (for example `winfsp-` and `.msi`, or `sshfs-win-` and
/// `-x64.msi`). The highest name wins when several versions are present.
fn installer_in(dir: &Path, prefix: &str, suffix: &str) -> Option<PathBuf> {
    let mut candidates: Vec<PathBuf> = std::fs::read_dir(dir)
        .ok()?
        .filter_map(|entry| entry.ok())
        .map(|entry| entry.path())
        .filter(|path| {
            path.is_file()
                && path
                    .file_name()
                    .and_then(|name| name.to_str())
                    .is_some_and(|name| {
                        let name = name.to_ascii_lowercase();
                        name.starts_with(prefix) && name.ends_with(suffix)
                    })
        })
        .collect();
    candidates.sort();
    candidates.pop()
}

/// Bundled installer for `prefix`/`suffix`, looking in `deps/` first.
fn bundled_installer(prefix: &str, suffix: &str) -> Option<PathBuf> {
    installer_dirs()
        .iter()
        .find_map(|dir| installer_in(dir, prefix, suffix))
}

/// Name of the temporary subdirectory holding extracted installers.
const TEMP_SUBDIR: &str = "aidesk-mount-wizard";

/// Writes an embedded MSI to `%TEMP%\aidesk-mount-wizard\<file_name>` and
/// returns its path. The file is rewritten on every call so a stale or
/// truncated copy from an interrupted run can never reach `msiexec`.
fn extract_installer(file_name: &str, bytes: &[u8]) -> Result<PathBuf, String> {
    let dir = std::env::temp_dir().join(TEMP_SUBDIR);
    std::fs::create_dir_all(&dir)
        .map_err(|err| format!("无法创建临时目录 {}：{err}", dir.display()))?;

    let path = dir.join(file_name);
    std::fs::write(&path, bytes)
        .map_err(|err| format!("无法写入临时文件 {}：{err}", path.display()))?;
    Ok(path)
}

/// `ERROR_INSTALL_USEREXIT`: the user closed the MSI wizard without installing.
const ERROR_INSTALL_USEREXIT: u32 = 1602;

fn open_download_page(url: &str) {
    if let Err(err) = win32::shell_execute("open", url, "") {
        crate::win32::error_box(&format!("无法打开下载页面 {url}：{err}"));
    }
}

/// One of the two bundled runtime components.
struct Component {
    /// Display name used in the user-facing messages.
    name: &'static str,
    /// File-name prefix of the MSI, used to find a bundled copy in `deps/`
    /// when this build did not embed one.
    msi_prefix: &'static str,
    /// File-name suffix of the MSI: `.msi` for the architecture-independent
    /// WinFsp package, `-x64.msi` / `-x86.msi` for SSHFS-Win.
    msi_suffix: &'static str,
    /// Installer compiled into the executable by `build.rs`, when present.
    embedded: Option<EmbeddedInstaller>,
    winget_id: &'static str,
    download_url: &'static str,
}

const WINFSP: Component = Component {
    name: "虚拟磁盘驱动（WinFsp）",
    msi_prefix: "winfsp-",
    msi_suffix: ".msi",
    embedded: WINFSP_INSTALLER,
    winget_id: "WinFsp.WinFsp",
    download_url: "https://github.com/winfsp/winfsp/releases/latest",
};

/// SSHFS-Win component for the running OS: the 64-bit client on 64-bit
/// Windows, the 32-bit client everywhere else. Both are embedded, so a single
/// 32-bit wizard covers every supported machine.
fn sshfs_component() -> Component {
    if is_os_64bit() {
        Component {
            name: "远程连接组件（SSHFS-Win）",
            msi_prefix: "sshfs-win-",
            msi_suffix: "-x64.msi",
            embedded: SSHFS_WIN_X64_INSTALLER,
            winget_id: "SSHFS-Win.SSHFS-Win",
            download_url: "https://github.com/winfsp/sshfs-win/releases/latest",
        }
    } else {
        Component {
            name: "远程连接组件（SSHFS-Win）",
            msi_prefix: "sshfs-win-",
            msi_suffix: "-x86.msi",
            embedded: SSHFS_WIN_X86_INSTALLER,
            winget_id: "SSHFS-Win.SSHFS-Win",
            download_url: "https://github.com/winfsp/sshfs-win/releases/latest",
        }
    }
}

impl Component {
    /// Path of the MSI handed to `msiexec`: the copy embedded in this
    /// executable first, then a `deps/` file for older archives.
    fn installer(&self) -> Result<PathBuf, String> {
        match self.embedded {
            Some((file_name, bytes)) => extract_installer(file_name, bytes),
            None => bundled_installer(self.msi_prefix, self.msi_suffix).ok_or_else(|| {
                format!("此构建未内嵌{}的安装包，也未在 deps 目录中找到", self.name)
            }),
        }
    }

    /// Installs the component: the embedded (or bundled) MSI first, then
    /// `winget`, then the upstream download page.
    ///
    /// Launching an installer is *synchronous*, so the caller's re-check right
    /// afterwards sees the real installation state instead of a process that
    /// has barely shown its first window.
    fn install(&self) -> Result<(), String> {
        let reason = match self.installer() {
            Ok(msi) => {
                let file_name = msi
                    .file_name()
                    .map(|name| name.to_string_lossy().into_owned())
                    .unwrap_or_default();
                let parameters = format!("/i \"{}\"", msi.display());
                match win32::shell_execute_wait("runas", "msiexec.exe", &parameters) {
                    Ok(code) if msi_succeeded(code) => return Ok(()),
                    Ok(ERROR_INSTALL_USEREXIT) => {
                        return Err(format!("已取消{}的安装。", self.name));
                    }
                    Ok(code) => {
                        format!("安装包 {file_name} 安装失败（退出码 {code}）")
                    }
                    Err(err) => format!("无法启动安装包 {file_name}（{err}）"),
                }
            }
            Err(reason) => reason,
        };

        let Some(winget) = winget_path() else {
            open_download_page(self.download_url);
            return Err(format!(
                "{reason}，且未检测到 winget；已打开 {} 的官方下载页面，安装后点击“重新检查”。",
                self.name
            ));
        };

        let parameters = format!(
            "install --id {} -e --accept-source-agreements --accept-package-agreements",
            self.winget_id
        );
        match win32::shell_execute_wait("runas", &winget, &parameters) {
            Ok(0) => Ok(()),
            Ok(code) => {
                open_download_page(self.download_url);
                Err(format!(
                    "{reason}，winget 安装亦失败（退出码 {code}）；已打开 {} 的官方下载页面。",
                    self.name
                ))
            }
            Err(err) => {
                open_download_page(self.download_url);
                Err(format!(
                    "{reason}，winget 启动失败（{err}）；已打开 {} 的官方下载页面。",
                    self.name
                ))
            }
        }
    }

    /// Removes the component: `msiexec /x` against the embedded or bundled
    /// package when it is available, otherwise `winget uninstall`.
    fn uninstall(&self) -> Result<(), String> {
        let reason = match self.installer() {
            Ok(msi) => {
                let file_name = msi
                    .file_name()
                    .map(|name| name.to_string_lossy().into_owned())
                    .unwrap_or_default();
                let parameters = format!("/x \"{}\"", msi.display());
                match win32::shell_execute_wait("runas", "msiexec.exe", &parameters) {
                    Ok(code) if msi_succeeded(code) => return Ok(()),
                    Ok(ERROR_INSTALL_USEREXIT) => {
                        return Err(format!("已取消{}的卸载。", self.name));
                    }
                    Ok(code) => {
                        format!("卸载包 {file_name} 未能卸载{0}（退出码 {code}）", self.name)
                    }
                    Err(err) => format!("无法启动卸载包 {file_name}（{err}）"),
                }
            }
            Err(reason) => reason,
        };

        let Some(winget) = winget_path() else {
            return Err(format!(
                "{reason}，且未检测到 winget；请在“设置 → 应用”中手动卸载。"
            ));
        };

        let parameters = format!(
            "uninstall --id {} -e --accept-source-agreements",
            self.winget_id
        );
        match win32::shell_execute_wait("runas", &winget, &parameters) {
            Ok(0) => Ok(()),
            Ok(code) => Err(format!(
                "{reason}，winget 卸载亦失败（退出码 {code}）；请在“设置 → 应用”中手动卸载。"
            )),
            Err(err) => Err(format!(
                "{reason}，winget 启动失败（{err}）；请在“设置 → 应用”中手动卸载。"
            )),
        }
    }
}

/// Installs the WinFsp driver (table row 1).
pub fn install_winfsp() -> Result<(), String> {
    WINFSP.install()
}

/// Installs the SSHFS-Win client matching the OS architecture (table row 2).
pub fn install_sshfs() -> Result<(), String> {
    sshfs_component().install()
}

/// Uninstalls the WinFsp driver (table row 1).
pub fn uninstall_winfsp() -> Result<(), String> {
    WINFSP.uninstall()
}

/// Uninstalls the SSHFS-Win client matching the OS architecture (table row 2).
pub fn uninstall_sshfs() -> Result<(), String> {
    sshfs_component().uninstall()
}

/// MSI exit codes that mean the product is installed: `0` (success), `3010`
/// and `1641` (success, with a pending reboot).
fn msi_succeeded(code: u32) -> bool {
    matches!(code, 0 | 3010 | 1641)
}
